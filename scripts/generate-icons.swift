// A multi-size ICO covers browsers requesting the conventional /favicon.ico.
func appendLE<T: FixedWidthInteger>(_ value: T, to data: inout Data) {
    var littleEndian = value.littleEndian
    withUnsafeBytes(of: &littleEndian) { data.append(contentsOf: $0) }
}
let sizes = [16, 32, 48]
let images = sizes.map { png(size: $0) }
var ico = Data()
appendLE(UInt16(0), to: &ico)
appendLE(UInt16(1), to: &ico)
appendLE(UInt16(sizes.count), to: &ico)
var offset = 6 + 16 * sizes.count
for (size, image) in zip(sizes, images) {
    ico.append(contentsOf: [UInt8(size), UInt8(size), 0, 0])
    appendLE(UInt16(1), to: &ico)
    appendLE(UInt16(32), to: &ico)
    appendLE(UInt32(image.count), to: &ico)
    appendLE(UInt32(offset), to: &ico)
    offset += image.count
}
for image in images { ico.append(image) }
try writeWebIcon(ico, to: "public/favicon.ico")

