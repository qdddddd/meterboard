import Foundation
import CoreGraphics
import ImageIO

// Run from the project root. Web and native icons share the page's palette
// and the same three rounded meter strips, ordered V2Free, Codex, Claude.
let stylesheet = try String(contentsOfFile: "public/styles.css", encoding: .utf8)
let palettePattern = try NSRegularExpression(pattern: #":root\s*\{([^}]+)\}"#)
let stylesheetRange = NSRange(stylesheet.startIndex..., in: stylesheet)
guard let paletteMatch = palettePattern.firstMatch(in: stylesheet, range: stylesheetRange),
      let paletteRange = Range(paletteMatch.range(at: 1), in: stylesheet) else {
    fatalError("Meterboard stylesheet has no :root palette")
}
let palette = String(stylesheet[paletteRange])

struct IconColor {
    let hex: String
    let cgColor: CGColor

    init(_ name: String) throws {
        let pattern = try NSRegularExpression(pattern: "--\(name):\\s*#([\\da-fA-F]{6})\\s*;")
        guard let match = pattern.firstMatch(in: palette, range: NSRange(palette.startIndex..., in: palette)),
              let range = Range(match.range(at: 1), in: palette),
              let value = UInt32(palette[range], radix: 16) else {
            fatalError("Expected a six-digit color for --\(name)")
        }
        hex = "#" + palette[range]
        cgColor = CGColor(colorSpace: CGColorSpace(name: CGColorSpace.sRGB)!, components: [
            CGFloat((value >> 16) & 255) / 255,
            CGFloat((value >> 8) & 255) / 255,
            CGFloat(value & 255) / 255, 1
        ])!
    }
}

let paper = try IconColor("paper")
let ink = try IconColor("ink")
// Match .backdrop in public/styles.css: a 4 px grid, solid to 0.55 px,
// fading out at 0.7 px, with 7% ink under a 70% opacity layer.
let grainSpacing: CGFloat = 4
let grainRadius: CGFloat = 0.7
let grainSolidStop: CGFloat = 0.55 / 0.7
let grainOpacity: CGFloat = 0.07 * 0.7
let grainGradient = CGGradient(colorsSpace: CGColorSpace(name: CGColorSpace.sRGB),
                               colors: [ink.cgColor.copy(alpha: grainOpacity)!,
                                        ink.cgColor.copy(alpha: grainOpacity)!,
                                        ink.cgColor.copy(alpha: 0)!] as CFArray,
                               locations: [0, grainSolidStop, 1])!
let grainTile: CGImage = {
    // Supersample the subpixel dot: a direct radial gradient can miss every
    // pixel center and disappear at this radius.
    let scale: CGFloat = 8
    let high = CGContext(data: nil, width: 32, height: 32, bitsPerComponent: 8, bytesPerRow: 128,
                         space: CGColorSpace(name: CGColorSpace.sRGB)!,
                         bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    high.scaleBy(x: scale, y: scale)
    let center = CGPoint(x: grainSpacing / 2, y: grainSpacing / 2)
    high.drawRadialGradient(grainGradient, startCenter: center, startRadius: 0,
                            endCenter: center, endRadius: grainRadius, options: [])
    let tile = CGContext(data: nil, width: 4, height: 4, bitsPerComponent: 8, bytesPerRow: 16,
                         space: CGColorSpace(name: CGColorSpace.sRGB)!,
                         bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    tile.interpolationQuality = .high
    tile.draw(high.makeImage()!, in: CGRect(x: 0, y: 0, width: grainSpacing, height: grainSpacing))
    return tile.makeImage()!
}()

func encodePNG(_ image: CGImage) -> Data {
    let output = NSMutableData()
    let destination = CGImageDestinationCreateWithData(output, "public.png" as CFString, 1, nil)!
    CGImageDestinationAddImage(destination, image, nil)
    precondition(CGImageDestinationFinalize(destination), "Could not encode icon PNG")
    return output as Data
}

let grainTileURL = "data:image/png;base64," + encodePNG(grainTile).base64EncodedString()
let paletteDemo = CommandLine.arguments.contains("--palette-demo")
let edgeDemo = CommandLine.arguments.contains("--edge-demo")
let colorNames = paletteDemo ? ["green", "cyan", "brown", "amber", "red"] : ["green", "cyan", "brown"]
let strips = try colorNames.map { try IconColor($0) }
let fullWidth = edgeDemo || paletteDemo
let stripX = fullWidth ? 0 : 4
let stripWidth = fullWidth ? 32 : 24
let stripRadius = fullWidth ? 0 : 2
let stripStep = paletteDemo ? 4 : 8
let svgStrips = strips.enumerated().map { index, color in
    "  <rect x=\"\(stripX)\" y=\"\(6 + index * stripStep)\" width=\"\(stripWidth)\" height=\"4\" rx=\"\(stripRadius)\" fill=\"\(color.hex)\"/>"
}.joined(separator: "\n")
func svg(size: Int) -> String {
    """
<!-- Generated by scripts/generate-icons.swift from public/styles.css. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 \(size) \(size)" width="\(size)" height="\(size)">
  <defs>
    <pattern id="paper-grain" width="\(grainSpacing)" height="\(grainSpacing)" patternUnits="userSpaceOnUse">
      <image width="\(grainSpacing)" height="\(grainSpacing)" href="\(grainTileURL)"/>
    </pattern>
  </defs>
  <rect width="\(size)" height="\(size)" fill="\(paper.hex)"/>
  <rect width="\(size)" height="\(size)" fill="url(#paper-grain)"/>
  <g transform="scale(\(CGFloat(size) / 32))">
\(svgStrips)
  </g>
</svg>

"""
}

func png(size: Int, native: Bool = false) -> Data {
    let alpha = native ? CGImageAlphaInfo.premultipliedLast : .noneSkipLast
    let context = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8,
                            bytesPerRow: size * 4, space: CGColorSpace(name: CGColorSpace.sRGB)!,
                            bitmapInfo: alpha.rawValue)!
    context.translateBy(x: 0, y: CGFloat(size))
    context.scaleBy(x: CGFloat(size) / 32, y: -CGFloat(size) / 32)
    if native {
        // Leave the usual transparent margin around a rounded Mac app tile.
        context.translateBy(x: 2, y: 2)
        context.scaleBy(x: 0.875, y: 0.875)
    }
    let background = CGPath(roundedRect: CGRect(x: 0, y: 0, width: 32, height: 32),
                            cornerWidth: native ? 6 : 0, cornerHeight: native ? 6 : 0, transform: nil)
    context.setFillColor(paper.cgColor)
    context.addPath(background)
    context.fillPath()
    context.saveGState()
    context.addPath(background)
    context.clip()
    // Render the grain at pixel size so larger icons keep a fine texture.
    context.scaleBy(x: 32 / CGFloat(size), y: 32 / CGFloat(size))
    context.draw(grainTile, in: CGRect(x: 0, y: 0, width: grainSpacing, height: grainSpacing), byTiling: true)
    context.restoreGState()
    for (index, color) in strips.enumerated() {
        context.setFillColor(color.cgColor)
        context.addPath(CGPath(roundedRect: CGRect(x: stripX, y: 6 + index * stripStep, width: stripWidth, height: 4),
                               cornerWidth: CGFloat(stripRadius), cornerHeight: CGFloat(stripRadius), transform: nil))
        context.fillPath()
    }
    return encodePNG(context.makeImage()!)
}

func write(_ data: Data, to path: String) throws {
    try data.write(to: URL(fileURLWithPath: path), options: .atomic)
}

func writeWebIcon(_ data: Data, to path: String) throws {
    try write(data, to: path)
    // Refreshed pages request a distinct URL from the previously cached icon.
    let url = URL(fileURLWithPath: path)
    try write(data, to: url.deletingPathExtension().path + "-v4." + url.pathExtension)
}

